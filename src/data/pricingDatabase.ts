// ============================================================================
// LOOKUP FUNCTIONS
// ============================================================================

export function getPricingByTrade(tradeId: TradeCategory): PricingEntry[] {
  return ALL_PRICING.filter((entry) => entry.tradeId === tradeId);
}

export function getPricingById(id: string): PricingEntry | undefined {
  return ALL_PRICING.find((entry) => entry.id === id);
}

export function getPricingByCategory(tradeId: TradeCategory, category: string): PricingEntry[] {
  return ALL_PRICING.filter((entry) => entry.tradeId === tradeId && entry.category === category);
}

export function getCategoriesByTrade(tradeId: TradeCategory): string[] {
  const entries = getPricingByTrade(tradeId);
  return [...new Set(entries.map((e) => e.category))];
}

export function searchPricing(query: string): PricingEntry[] {
  const lowerQuery = query.toLowerCase();
  return ALL_PRICING.filter(
    (entry) =>
      entry.item.toLowerCase().includes(lowerQuery) ||
      entry.category.toLowerCase().includes(lowerQuery) ||
      entry.partNumber?.toLowerCase().includes(lowerQuery) ||
      entry.brand?.toLowerCase().includes(lowerQuery)
  );
}

export function getPricingBySupplier(supplierCode: string): PricingEntry[] {
  return ALL_PRICING.filter((entry) => entry.supplier === supplierCode);
}

export function getPricingByBrand(brand: string): PricingEntry[] {
  return ALL_PRICING.filter((entry) => entry.brand?.toLowerCase() === brand.toLowerCase());
}
